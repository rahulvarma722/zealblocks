#!/usr/bin/env bash
#
# Builds a WordPress.org-ready ZIP.
#
#   ./bin/build-zip.sh              # build dist/zealblocks-<version>.zip
#   ./bin/build-zip.sh --check      # ...then run Plugin Check on the ARTIFACT
#
# WHY THIS SCRIPT EXISTS. Two facts about this repo fight each other:
#
#   1. `build/` is in .gitignore, but blocks are registered by scanning
#      build/ (includes/class-blocks.php). A ZIP made from a git
#      archive therefore installs cleanly and registers ZERO blocks.
#   2. node_modules/ is ~550 MB and sits in the plugin root. The .org
#      upload form caps at 10 MB.
#
# So neither `git archive` nor `zip -r . ` produces a valid package. This
# builds from an explicit allow-list instead: anything not named below is
# absent by construction, which is the only way a packaging script stays
# correct as the tree grows.
#
# NO DEVELOPMENT FILES. The payload is runtime code plus the two files the
# directory requires, and nothing else.
#
# src/ and package.json used to ship. They were 106 KB of a 112 KB archive —
# more than the code that actually runs — and 28 KB of that was byte-identical
# duplication, because wp-scripts copies render.php and block.json into build/
# verbatim. Nothing in src/ is ever loaded: blocks register from build/.
#
# Guideline 4 still applies, because the shipped JS is minified. It is satisfied
# the other way the guideline allows: by documenting the source in readme.txt.
# The assertion below holds the readme and the payload together, so dropping
# src/ cannot silently drop the disclosure with it.

# Output goes to dist/, which is gitignored and excluded from the payload.
# Note that running Plugin Check against the WORKING TREE will flag dist/,
# bin/, docs/ and .gitignore — that is expected and says nothing about
# the artifact. Scan the extracted ZIP if you want a meaningful result.

set -euo pipefail

cd "$( dirname "${BASH_SOURCE[0]}" )/.."

SLUG="zealblocks"
MAIN_FILE="${SLUG}.php"
DIST="dist"
RUN_CHECK=0

[[ "${1:-}" == "--check" ]] && RUN_CHECK=1

die() { printf '\033[31merror:\033[0m %s\n' "$1" >&2; exit 1; }
ok()  { printf '\033[32m  ok\033[0m  %s\n' "$1"; }
warn(){ printf '\033[33mwarn:\033[0m %s\n' "$1" >&2; }

# ---------------------------------------------------------------------
# Everything that ships. Directories are copied whole; see PRUNE below.
# ---------------------------------------------------------------------
PAYLOAD=(
	"$MAIN_FILE"
	"readme.txt"
	"LICENSE"
	"includes"
	"build"
)

# Removed after copying. `build/` is generated by wp-scripts, which leaves
# *.asset.php (needed) alongside source maps and RTL duplicates of empty
# stylesheets (not needed, and reviewers flag map files as unreadable code).
PRUNE_GLOBS=( "*.map" ".DS_Store" "*.LICENSE.txt" )

# ---------------------------------------------------------------------
# Preflight. Each of these has been an actual .org rejection.
# ---------------------------------------------------------------------
printf '\n\033[1mPreflight\033[0m\n'

[[ -f "$MAIN_FILE" ]] || die "$MAIN_FILE not found — run from the plugin root."
[[ -f "readme.txt" ]] || die "readme.txt is missing. The .org upload form rejects the ZIP without it."
[[ -f "LICENSE"    ]] || die "LICENSE is missing (Guideline 1: GPL text must ship)."

# Version must agree in three places or users get no update prompt.
HEADER_VERSION=$( grep -m1 '^\s*\*\s*Version:' "$MAIN_FILE" | sed -E 's/.*Version:[[:space:]]*//' | tr -d '[:space:]' )
CONST_VERSION=$( grep -m1 "define( 'ZEALBLOCKS_VERSION'" "$MAIN_FILE" | sed -E "s/.*'([^']+)'[^']*\)?;?$/\1/" )
README_STABLE=$( grep -m1 '^Stable tag:' readme.txt | sed -E 's/^Stable tag:[[:space:]]*//' | tr -d '[:space:]' )

[[ -n "$HEADER_VERSION" ]] || die "could not read Version from $MAIN_FILE."
[[ "$HEADER_VERSION" == "$CONST_VERSION" ]] \
	|| die "version mismatch: header $HEADER_VERSION vs ZEALBLOCKS_VERSION $CONST_VERSION."
[[ "$HEADER_VERSION" == "$README_STABLE" ]] \
	|| die "version mismatch: header $HEADER_VERSION vs readme Stable tag $README_STABLE."
ok "version $HEADER_VERSION consistent across header, constant and Stable tag"

[[ "$README_STABLE" == "trunk" ]] && die "Stable tag must be a real tag, never 'trunk'."

# Placeholders. A readme that still says REPLACE_ gets bounced on sight.
if grep -qE 'REPLACE_WITH|example\.com|TODO|FIXME|XXX' readme.txt "$MAIN_FILE"; then
	grep -nE 'REPLACE_WITH|example\.com|TODO|FIXME|XXX' readme.txt "$MAIN_FILE" >&2 || true
	die "placeholder text above must be filled in before packaging."
fi
ok "no placeholder text in readme.txt or $MAIN_FILE"

# Required readme headers. `Contributors` is deliberately NOT in this list: it
# is optional on WordPress.org, and blocking on it would mean either holding the
# build hostage or inventing a username — which becomes a permanent public
# attribution on the directory page. Warned about below instead.
for field in "Tags" "Requires at least" "Tested up to" "Requires PHP" "Stable tag" "License" "License URI"; do
	grep -q "^${field}:" readme.txt || die "readme.txt is missing the '${field}:' header."
done
ok "all required readme.txt headers present"

if grep -q "^Contributors:" readme.txt; then
	ok "Contributors set"
else
	warn "readme.txt has no 'Contributors:' header — the directory page will credit nobody."
	warn "     Add 'Contributors:      <your-wordpress.org-username>' as line 2 before submitting."
fi

# Short description: the line after the header block, capped at 150 chars by
# .org. Over the cap it is silently truncated on the directory page, which is
# how plugins end up with a sentence that stops mid-word.
SHORT_DESC=$( awk 'NR>1 && /^[A-Za-z ]+:/ {next} NR>1 && NF {print; exit}' readme.txt )
DESC_LEN=${#SHORT_DESC}
(( DESC_LEN > 0 )) || die "readme.txt has no short description line after the headers."
(( DESC_LEN <= 150 )) || die "short description is $DESC_LEN chars; the maximum is 150."
ok "short description $DESC_LEN chars (max 150)"

# .org allows a maximum of five tags.
TAG_COUNT=$( grep -m1 '^Tags:' readme.txt | sed -E 's/^Tags:[[:space:]]*//' | tr ',' '\n' | sed '/^[[:space:]]*$/d' | wc -l | tr -d ' ' )
(( TAG_COUNT <= 5 )) || die "readme.txt lists $TAG_COUNT tags; the maximum is 5."
ok "$TAG_COUNT tags (max 5)"


# Stale build. Shipping yesterday's bundle is silent and maddening.
#
# BUILT, not checked. Two mtime-based attempts at detecting staleness were both
# wrong, for the same underlying reason: webpack does not rewrite an asset whose
# content is unchanged ("compared for emit"), so a source file touched without
# changing its output leaves build/ legitimately older than src/ forever. No
# comparison of timestamps can tell that apart from a genuinely stale build.
#
# Running the build removes the question. It takes well under a second, it is
# idempotent, and afterwards build/ is current by construction.
#
# NODE_ENV is pinned rather than inherited. wp-scripts picks its webpack mode
# from NODE_ENV, so whatever the operator happens to have exported decides
# whether the RELEASE artifact is minified. A shell with NODE_ENV=development
# silently produced a dev build — unminified, source comments and all — that
# passed every other check in this script and would have shipped.
if [[ -x node_modules/.bin/wp-scripts ]]; then
	NODE_ENV=production node_modules/.bin/wp-scripts build >/dev/null 2>&1 || die "the build failed; run 'npm run build' to see why."
	ok "build/ regenerated from src/ (production mode)"
else
	warn "node_modules absent — could not rebuild; build/ is being shipped as found"
fi

# The build/ trap. Checked AFTER the build above, not before: this asks whether
# the OUTPUT is well-formed, and a clean checkout (or a `rm -rf build`) has no
# build/ at all. Checking first made the script refuse to run for the exact
# reason it was about to fix itself.
[[ -d "build" ]] || die "build/ is missing and could not be generated. Run 'npm run build' — blocks are registered from build/, so the plugin does nothing without it."
for d in build/*/; do
	[[ -f "${d}block.json" ]] || die "${d} has no block.json; the build looks incomplete."
done
BLOCK_COUNT=$( find build -mindepth 2 -maxdepth 2 -name block.json | wc -l | tr -d ' ' )
(( BLOCK_COUNT > 0 )) || die "build/ contains no blocks."
ok "build/ holds $BLOCK_COUNT block(s)"

# Debug artifacts that must not reach a user.
if grep -rqE 'SHOW_DIAGNOSTICS = true' src/ 2>/dev/null; then
	die "SHOW_DIAGNOSTICS is true — the diagnostics <pre> would render in the inspector."
fi
if grep -rqE 'console\.(log|debug|warn)|\bvar_dump\(|\berror_log\(|\bprint_r\(' src/ includes/ "$MAIN_FILE" 2>/dev/null; then
	grep -rnE 'console\.(log|debug|warn)|\bvar_dump\(|\berror_log\(|\bprint_r\(' src/ includes/ "$MAIN_FILE" >&2 || true
	die "debug statements above must be removed."
fi
ok "no debug artifacts"

# Direct-access guards.
#
# `*.asset.php` is exempt. wp-scripts generates those as a bare
# `<?php return array( 'dependencies' => …, 'version' => … );` — they emit
# nothing when hit directly, register_block_type() reads them with require,
# and every block plugin on .org ships them unguarded. Adding a guard would
# break the return.
while IFS= read -r php; do
	grep -q "defined( 'ABSPATH' )" "$php" || die "$php has no ABSPATH guard."
done < <( find "$MAIN_FILE" includes build -name '*.php' ! -name '*.asset.php' 2>/dev/null )
ok "every shipped PHP file has an ABSPATH guard (*.asset.php exempt)"

# PHPCS. The real standards gate — php -l below only catches parse errors.
# Skipped rather than failed when the toolchain is absent, so the script still
# works on a clean checkout before `composer install`.
if [[ -x vendor/bin/phpcs ]]; then
	vendor/bin/phpcs --report=summary -q || die "PHPCS reported violations. Run 'composer format' then fix what remains."
	ok "PHPCS clean (WordPress-Extra, WordPress-Docs, PHPCompatibilityWP)"
else
	warn "vendor/bin/phpcs absent — run 'composer install' to enable the standards gate"
fi

# Tests. The unit suites need no WordPress and take under a second between
# them, so there is no reason for a release not to run them. The integration
# suite needs a live WordPress and is therefore opt-in via `--check` / CI, not a
# hard gate here — a release should not be blocked by wp-cli being absent.
if [[ -x vendor/bin/phpunit ]]; then
	vendor/bin/phpunit --no-progress >/dev/null 2>&1 || die "PHPUnit failures. Run 'composer test'."
	ok "PHPUnit unit suite passing"
else
	warn "vendor/bin/phpunit absent — run 'composer install' to enable the unit suite"
fi

if [[ -x node_modules/.bin/wp-scripts ]]; then
	node_modules/.bin/wp-scripts test-unit-js >/dev/null 2>&1 || die "Jest failures. Run 'npm run test:js'."
	ok "Jest unit suite passing"
fi

# JS and CSS standards. Same reasoning as PHPCS: skipped rather than failed
# when node_modules is absent, so the script works on a clean checkout.
if [[ -x node_modules/.bin/wp-scripts ]]; then
	node_modules/.bin/wp-scripts lint-js >/dev/null 2>&1 || die "ESLint reported violations. Run 'npm run lint:js -- --fix'."
	node_modules/.bin/wp-scripts lint-style >/dev/null 2>&1 || die "Stylelint reported violations. Run 'npm run lint:css -- --fix'."
	ok "ESLint and Stylelint clean"
else
	warn "node_modules absent — skipped the JS/CSS standards gate"
fi

# PHP syntax, if a CLI is around.
if command -v php >/dev/null 2>&1; then
	while IFS= read -r php; do
		php -l "$php" >/dev/null || die "PHP syntax error in $php"
	done < <( find "$MAIN_FILE" includes build -name '*.php' 2>/dev/null )
	ok "PHP syntax clean ($(php -r 'echo PHP_VERSION;'))"
else
	warn "php not on PATH — skipped the syntax check"
fi

# ---------------------------------------------------------------------
# Stage
# ---------------------------------------------------------------------
printf '\n\033[1mStaging\033[0m\n'

STAGE=$( mktemp -d )
trap 'rm -rf "$STAGE"' EXIT
ROOT="$STAGE/$SLUG"
mkdir -p "$ROOT"

for item in "${PAYLOAD[@]}"; do
	if [[ -e "$item" ]]; then
		cp -R "$item" "$ROOT/"
		ok "$item"
	else
		warn "$item not found — skipped"
	fi
done

for glob in "${PRUNE_GLOBS[@]}"; do
	find "$ROOT" -name "$glob" -delete 2>/dev/null || true
done

# Belt and braces: these must never be in the tree, whatever the allow-list says.
for forbidden in node_modules vendor .git .github .gitignore .eslintrc.js .eslintrc .stylelintrc package-lock.json composer.json composer.lock phpcs.xml.dist phpcs.xml phpunit.xml.dist phpunit.xml .phpunit.cache tests docs bin dist; do
	if [[ -e "$ROOT/$forbidden" ]]; then
		rm -rf "$ROOT/$forbidden"
		warn "removed unexpected $forbidden from the staged tree"
	fi
done

# ---------------------------------------------------------------------
# Verify the STAGED TREE, not the working tree.
#
# This is the part that matters. The working tree legitimately holds things
# that must never ship — bin/, docs/, .gitignore, node_modules/ — so running
# Plugin Check against the repo reports errors that say nothing about the
# artifact. These assertions run against exactly what goes into the ZIP,
# and each mirrors a Plugin Check rule that is an ERROR, not a warning.
# ---------------------------------------------------------------------
printf '\n\033[1mVerifying staged tree\033[0m\n'

# plugin-check: hidden_files (ERROR). Includes .gitkeep, .DS_Store, .env.
HIDDEN=$( find "$ROOT" -name '.*' ! -name '.' ! -name '..' 2>/dev/null || true )
if [[ -n "$HIDDEN" ]]; then
	printf '%s\n' "$HIDDEN" >&2
	die "hidden files above would ship; Plugin Check reports these as errors."
fi
ok "no hidden files"

# plugin-check: application_detected (ERROR). Shell scripts, binaries, phars.
APPS=$( find "$ROOT" \( -name '*.sh' -o -name '*.bat' -o -name '*.exe' -o -name '*.phar' -o -name '*.so' -o -name '*.dll' \) 2>/dev/null || true )
if [[ -n "$APPS" ]]; then
	printf '%s\n' "$APPS" >&2
	die "application files above would ship; Plugin Check reports these as errors."
fi
ok "no application files"

# Developer FAQ: "Compressed files (zips) cannot be included."
ARCHIVES=$( find "$ROOT" \( -name '*.zip' -o -name '*.tar' -o -name '*.gz' -o -name '*.rar' -o -name '*.7z' \) 2>/dev/null || true )
if [[ -n "$ARCHIVES" ]]; then
	printf '%s\n' "$ARCHIVES" >&2
	die "archives above would ship; compressed files are not permitted inside a plugin."
fi
ok "no nested archives"

# plugin-check: unexpected_markdown_file. Only readme/license markdown is
# expected in a production plugin root.
MD=$( find "$ROOT" -maxdepth 1 -name '*.md' 2>/dev/null || true )
if [[ -n "$MD" ]]; then
	printf '%s\n' "$MD" >&2
	die "markdown above would ship from the plugin root; move developer docs out of the payload."
fi
ok "no stray markdown in the plugin root"

# Guideline 13: no bundled copies of libraries WordPress already packages.
VENDORED=$( find "$ROOT" \( -iname 'jquery*.js' -o -iname 'lodash*.js' -o -iname 'react*.js' -o -iname 'moment*.js' \) 2>/dev/null || true )
if [[ -n "$VENDORED" ]]; then
	printf '%s\n' "$VENDORED" >&2
	die "files above look like copies of libraries WordPress already bundles (Guideline 13)."
fi
ok "no bundled core libraries"

# NO DEVELOPMENT FILES — asserted as an ALLOW-LIST on the artifact.
#
# The PAYLOAD list already means nothing else is copied, but that is a statement
# about the code above; this is a statement about the RESULT. Anything that
# reaches the staged tree without being named here fails the build, which is
# what makes "no development files in the ZIP" a rule rather than an intention.
#
# Stronger than a blocklist on purpose: a blocklist has to predict what someone
# will add next.
EXPECTED_ROOT=( "$MAIN_FILE" "readme.txt" "LICENSE" "includes" "build" )

while IFS= read -r entry; do
	name="$( basename "$entry" )"
	permitted=0

	for allowed in "${EXPECTED_ROOT[@]}"; do
		[[ "$name" == "$allowed" ]] && permitted=1 && break
	done

	if (( ! permitted )); then
		die "unexpected entry in the package: $name — the payload is runtime code plus readme.txt and LICENSE, nothing else."
	fi
done < <( find "$ROOT" -mindepth 1 -maxdepth 1 )

ok "package contains only runtime code, readme.txt and LICENSE"

# Named development files, checked individually so the failure says which one.
for dev in src package.json package-lock.json composer.json composer.lock \
	node_modules vendor tests docs bin phpcs.xml.dist phpunit.xml.dist \
	.eslintrc.js .gitignore .github; do
	[[ -e "$ROOT/$dev" ]] && die "development file in the package: $dev"
done
ok "no development files"

# Guideline 4: the shipped JS is minified, so the source has to be reachable.
# src/ no longer ships, which means the readme disclosure is now the ONLY thing
# satisfying it — so it is verified rather than assumed.
if ! grep -qE 'https?://[^ ]+' readme.txt; then
	die "readme.txt must document where the unminified source lives (Guideline 4), since src/ is not shipped."
fi
ok "readme documents the source location (Guideline 4)"

if [[ -d "$ROOT/src" ]]; then
	die "src/ is in the package but the readme points elsewhere for source — pick one."
fi

# The plugin must actually be loadable: main file parseable and headers intact.
for header in "Plugin Name" "Description" "Version" "Requires at least" "Requires PHP" "License" "Text Domain"; do
	grep -qE "^\s*\*\s*${header}:" "$ROOT/$MAIN_FILE" || die "$MAIN_FILE is missing the '${header}:' header."
done
ok "all required plugin headers present in the staged main file"

# ...and must NOT carry readme-only headers.
#
# "Tested up to" is a README header, not a plugin header. Declared in both
# files the values can disagree, and the main-file one may win — so the
# directory page, the search index and the compatibility notice can advertise a
# version nobody is maintaining. The Plugin Review Team flagged exactly this
# (review P0TDX362558HGN), so it is asserted here rather than trusted to
# reappear unnoticed on the next header edit.
for header in "Tested up to" "Tags" "Stable tag" "Contributors"; do
	if grep -qE "^\s*\*\s*${header}:" "$ROOT/$MAIN_FILE"; then
		die "$MAIN_FILE declares '${header}:', which belongs only in readme.txt. WordPress.org treats it as a readme header; in both files the values can disagree and the wrong one can win."
	fi
done
ok "no readme-only headers in the staged main file"

# ---------------------------------------------------------------------
# Zip
# ---------------------------------------------------------------------
printf '\n\033[1mPackaging\033[0m\n'

# CLEAR dist/ COMPLETELY, not just this version's filename.
#
# `rm -f "$ZIP"` alone was not enough. It replaced the current version but left
# every previous one sitting there, so dist/ accumulated builds and it stopped
# being obvious which file was the one you just made — the exact situation where
# somebody uploads zealblocks-0.0.1.zip to .org an hour after bumping to 0.0.2.
#
# Removals are listed rather than done quietly, so the delete-then-create is
# visible in the output.
mkdir -p "$DIST"

for stale in "$DIST"/*.zip; do
	[[ -e "$stale" ]] || continue
	rm -f "$stale"
	ok "removed $stale"
done

ZIP="$( pwd )/$DIST/${SLUG}-${HEADER_VERSION}.zip"

( cd "$STAGE" && zip -rq "$ZIP" "$SLUG" -x '*.DS_Store' )

SIZE_BYTES=$( wc -c < "$ZIP" | tr -d ' ' )
SIZE_HUMAN=$( du -h "$ZIP" | cut -f1 | tr -d ' ' )
LIMIT=$(( 10 * 1024 * 1024 ))

if (( SIZE_BYTES > LIMIT )); then
	die "ZIP is $SIZE_HUMAN, over the 10 MB .org upload limit."
fi
ok "$SIZE_HUMAN (limit 10 MB)"

printf '\n\033[1mContents\033[0m\n'
unzip -Z1 "$ZIP" | sed 's/^/  /'

printf '\n\033[1;32mBuilt\033[0m %s\n' "$DIST/${SLUG}-${HEADER_VERSION}.zip"

# ---------------------------------------------------------------------
# Optional: Plugin Check against the ARTIFACT.
#
# Pointing Plugin Check at the working tree is misleading — the repo
# legitimately holds bin/, dist/, .github/, .eslintrc.js, phpcs.xml.dist,
# .gitignore and docs/, none of which ship, so a scan of it reports a
# fistful of errors that say nothing about the submission. Worse, it trains you
# to skim past them, which is how a real finding gets missed.
#
# This installs the extracted ZIP alongside, scans THAT, and cleans up.
# ---------------------------------------------------------------------
if (( RUN_CHECK )); then
	printf '\n\033[1mPlugin Check (release artifact)\033[0m\n'

	WP="${WP_CLI:-wp}"

	if ! command -v "$WP" >/dev/null 2>&1; then
		warn "wp-cli not found; skipped. Set WP_CLI=/path/to/wp, or 'brew install wp-cli'."
	else
		CHECK_SLUG="${SLUG}-relcheck"
		CHECK_DIR="$( cd .. && pwd )/${CHECK_SLUG}"
		EXTRACT="$( mktemp -d )"

		rm -rf "$CHECK_DIR"
		unzip -q "$ZIP" -d "$EXTRACT"
		cp -R "${EXTRACT}/${SLUG}" "$CHECK_DIR"

		# Plugin Check derives the expected text domain from the DIRECTORY name,
		# so a copy scanned as anything but "zealblocks" reports a mismatch on
		# every translated string. Those two codes are filtered; nothing else is.
		CHECK_OUT="$( "$WP" plugin check "$CHECK_SLUG" \
			--categories=general,plugin_repo,security,performance,accessibility \
			--format=csv --fields=file,line,type,code,message 2>&1 \
			| grep -vE 'TextDomainMismatch|textdomain_mismatch' || true )"

		rm -rf "$CHECK_DIR" "$EXTRACT"

		CHECK_HITS="$( printf '%s\n' "$CHECK_OUT" | grep -cE ',(ERROR|WARNING),' || true )"

		if [[ "${CHECK_HITS:-0}" -eq 0 ]]; then
			ok "no findings in the artifact (text-domain mismatches filtered: dir is ${CHECK_SLUG})"
		else
			printf '%s\n' "$CHECK_OUT" >&2
			die "$CHECK_HITS Plugin Check finding(s) in the artifact, listed above."
		fi
	fi
fi

printf '\nNext:\n'
printf '  1. Install this ZIP on a clean site and confirm both blocks appear.\n'
printf '  2. Upload at https://wordpress.org/plugins/developers/add/\n'
printf '  3. On approval: commit to SVN trunk/, then  svn cp trunk tags/%s\n' "$HEADER_VERSION"
printf '  4. Put icon/banner/screenshot files in the SVN assets/ directory, NOT in this ZIP.\n\n'
